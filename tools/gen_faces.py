#!/usr/bin/env python3
"""Render the Pwnagotchi text faces into 1-bit bitmaps for the ESP32.

The expressions and the DejaVuSansMono-Bold font are the same assets the
upstream Pwnagotchi UI uses. The rendered bitmaps are packed MSB-first, one
bit per pixel, with 1 meaning ink, and written to face_assets.h.
"""

from __future__ import annotations

import argparse
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

# pwnagotchi/ui/faces.py
FACES = {
    "AWAKE": "(◕‿‿◕)",
    "LOOK_R": "( ⚆_⚆)",
    "LOOK_L": "(☉_☉ )",
    "HAPPY": "(•‿‿•)",
    "EXCITED": "(ᵔ◡◡ᵔ)",
    "FRIEND": "(♥‿‿♥)",
    "SLEEP": "(⇀‿‿↼)",
    "BORED": "(-__-)",
}

WIDTH = 170
HEIGHT = 58
FONT_SIZE = 45


def pack_1bit(img: Image.Image) -> bytes:
    w, h = img.size
    row_bytes = (w + 7) // 8
    out = bytearray(row_bytes * h)
    for y in range(h):
        for x in range(w):
            if img.getpixel((x, y)) < 128:
                out[y * row_bytes + (x // 8)] |= 0x80 >> (x % 8)
    return bytes(out)


def c_array(name: str, data: bytes) -> str:
    lines = [f"static const uint8_t FACE_{name}[] PROGMEM = {{"]
    for i in range(0, len(data), 12):
        chunk = data[i:i + 12]
        lines.append("  " + ", ".join(f"0x{b:02X}" for b in chunk) + ",")
    lines.append("};")
    return "\n".join(lines)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--font", default="assets/DejaVuSansMono-Bold.ttf")
    ap.add_argument("--out", default="firmware/pwnagotchi/face_assets.h")
    ap.add_argument("--preview", default="assets/faces_preview.png")
    args = ap.parse_args()

    font = ImageFont.truetype(args.font, FONT_SIZE)
    cell = font.getlength(FACES["AWAKE"])
    x = (WIDTH - cell) / 2.0

    arrays = []
    preview = Image.new("RGB", (WIDTH * 2, HEIGHT * 4), "white")

    for i, (name, text) in enumerate(FACES.items()):
        img = Image.new("L", (WIDTH, HEIGHT), 255)
        draw = ImageDraw.Draw(img)
        # anchor=lm keeps the monospace cell intact, so the leading/trailing
        # spaces in LOOK_R / LOOK_L still shift the eyes left and right.
        draw.text((x, HEIGHT / 2), text, font=font, fill=0, anchor="lm")
        data = pack_1bit(img)
        arrays.append(c_array(name, data))

        px = (i % 2) * WIDTH
        py = (i // 2) * HEIGHT
        preview.paste(img.convert("RGB"), (px, py))

    header = [
        "// Generated by tools/gen_faces.py. Do not edit by hand.",
        "// Face expressions from Pwnagotchi (evilsocket/pwnagotchi), GPL-3.0.",
        "// Rendered with DejaVuSansMono-Bold, Bitstream Vera license.",
        "#pragma once",
        "#include <stdint.h>",
        "#ifndef PROGMEM",
        "#define PROGMEM",
        "#endif",
        "",
        "struct FaceBitmap {",
        "  const uint8_t *data;",
        "  uint16_t w;",
        "  uint16_t h;",
        "};",
        "",
    ]
    header.extend(arrays)
    header.append("")
    header.append("enum FaceIndex : uint8_t {")
    for i, name in enumerate(FACES):
        header.append(f"  FACE_ID_{name} = {i},")
    header.append("};")
    header.append("")
    header.append("static const FaceBitmap FACE_TABLE[] = {")
    for name in FACES:
        header.append(f"  {{FACE_{name}, {WIDTH}, {HEIGHT}}},")
    header.append("};")
    header.append("")

    Path(args.out).write_text("\n".join(header))
    Path(args.preview).parent.mkdir(parents=True, exist_ok=True)
    preview.save(args.preview)
    print(f"wrote {args.out} ({len(arrays)} faces)")
    print(f"wrote {args.preview}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
